# 使用冻结Joint20参考运行MSCCR CD+UC全队列，保存完整posterior并核对fraction。
# 服务器bayesprism 2.2.3环境运行；不启动EcoTyper，不改变原始非整数counts。
suppressPackageStartupMessages(library(BayesPrism))
suppressPackageStartupMessages(library(Matrix))
options(stringsAsFactors = FALSE, warn = 1)
out <- commandArgs(trailingOnly = TRUE)[1]
writeLines(as.character(Sys.getpid()), file.path(out, 'logs/formal_R.pid'))

# Step1. 读取审计通过的固定样本和已清理同源参考
stopifnot(file.exists(file.path(out, '00_audit/input_audit.json')), as.character(packageVersion('BayesPrism')) == '2.2.3')
annotation <- read.delim(file.path(out, '00_audit/MSCCR_CD_UC_discovery_manifest.tsv'), check.names = FALSE)
types <- readLines(file.path(out, '00_audit/frozen_types.txt'))
cells <- read.delim(file.path(out, '01_reference/reference_cells.tsv'), check.names = FALSE)
ref <- readRDS(file.path(out, '01_reference/clean_reference.rds'))
stopifnot(identical(ref$labels, cells$coarse_identity), identical(ref$types, types), nrow(ref$reference) == 9294, length(unique(ref$labels)) == 20)
stopifnot(identical(rownames(ref$reference), cells$cell_id), !anyDuplicated(colnames(ref$reference)), all(rowSums(ref$reference) > 0))
stopifnot(all(annotation$Disease %in% c('CD', 'UC')), !anyDuplicated(annotation$ID))
writeLines(capture.output(sessionInfo()), file.path(out, 'logs/R_sessionInfo.txt'))
ns <- asNamespace('BayesPrism')
source_functions <- c('get.exp', 'run.prism', 'valid.gibbs.control', 'valid.opt.control', 'run.gibbs.refPhi.ini', 'run.gibbs.refPhi.final', 'run.gibbs')
for (name in source_functions) writeLines(c(name, deparse(get(name, ns))), file.path(out, '00_audit', paste0(name, '_installed.R')))
print(table(annotation$Disease, annotation$Inflammation))
print(table(ref$labels))

# Step2. 使用与benchmark相同的基因规则，按完整队列冻结outlier过滤
bulk <- read.delim(gzfile(file.path(out, '02_bayesprism/mixture_raw_counts.tsv.gz')), row.names = 1, check.names = FALSE)
mixture <- t(as.matrix(bulk))
stopifnot(identical(rownames(mixture), annotation$ID), all(is.finite(mixture)), all(mixture >= 0), all(rowSums(mixture) > 0), !anyDuplicated(colnames(mixture)))
fractional_before <- rowSums(mixture != round(mixture))
prism <- new.prism(reference = ref$reference, input.type = 'count.matrix', cell.type.labels = ref$labels, cell.state.labels = ref$labels, key = NULL, mixture = mixture, outlier.cut = 0.01, outlier.fraction = 0.1, pseudo.min = 1e-8)
stopifnot(identical(rownames(prism@mixture), annotation$ID), setequal(rownames(prism@phi_cellType@phi), types), identical(colnames(prism@mixture), colnames(prism@phi_cellType@phi)))
gene_audit <- data.frame(gene = colnames(mixture), retained_after_cleanup = colnames(mixture) %in% colnames(ref$reference), retained_in_prism = colnames(mixture) %in% colnames(prism@mixture))
write.table(gene_audit, file.path(out, '02_bayesprism/gene_filter_audit.tsv'), sep = '\t', row.names = FALSE, quote = FALSE)
write.table(data.frame(ID = annotation$ID, fractional_before = fractional_before, fractional_in_prism = rowSums(prism@mixture != round(prism@mixture)), retained_counts = rowSums(prism@mixture)), file.path(out, '02_bayesprism/prism_sample_audit.tsv'), sep = '\t', row.names = FALSE, quote = FALSE)
writeLines(colnames(prism@mixture), file.path(out, '02_bayesprism/retained_genes.txt'))
saveRDS(prism, file.path(out, '02_bayesprism/prism_input.rds'), compress = FALSE)
print(dim(prism@mixture))

# Step3. 保持benchmark随机种子、8核和已安装默认Gibbs及优化参数
set.seed(20261013)
writeLines(capture.output(get('valid.gibbs.control', ns)(list())), file.path(out, '02_bayesprism/gibbs_defaults.txt'))
writeLines(capture.output(get('valid.opt.control', ns)(list())), file.path(out, '02_bayesprism/opt_defaults.txt'))
writeLines(c('seed 20261013', 'n.cores 8', 'update.gibbs TRUE', 'outlier.cut 0.01', 'outlier.fraction 0.1', 'pseudo.min 1e-8', 'key NULL', 'input.type count.matrix', 'cleanup reused benchmark: Rb,Mrp,other_Rb,chrM,MALAT1,chrX,chrY; exp.cells=1', 'reference: 9294 original cells, 20 states identical to 20 parent types', 'fractional counts preserved; internal rmultinom integer-size limitation retained'), file.path(out, '02_bayesprism/run_parameters.txt'))
cat('Outer R seed 20261013; installed Gibbs default seed 123, chain.length 1000, burn.in 500, thinning 2; unchanged from benchmark\n')
rm(ref, bulk, mixture)
gc()
writeLines(paste('GIBBS_STARTED', format(Sys.time(), tz = 'Asia/Shanghai', usetz = TRUE)), file.path(out, 'logs/current_stage.txt'))
cat('FORMAL_RUN_PRISM_START', format(Sys.time(), tz = 'Asia/Shanghai', usetz = TRUE), '\n')
flush.console()
bp <- run.prism(prism = prism, n.cores = 8, update.gibbs = TRUE)
saveRDS(bp, file.path(out, '02_bayesprism/BayesPrism_result.rds'), compress = FALSE)
writeLines(capture.output(str(bp@control_param)), file.path(out, '02_bayesprism/actual_control_parameters.txt'))

# Step4. 验证并导出初始、最终theta和对应CV；保留完整Z在结果对象内
initial <- get.fraction(bp, which.theta = 'first', state.or.type = 'type')
final <- get.fraction(bp, which.theta = 'final', state.or.type = 'type')
stopifnot(identical(rownames(final), annotation$ID), setequal(colnames(final), types), all(is.finite(initial)), all(initial >= 0), all(is.finite(final)), all(final >= 0))
stopifnot(max(abs(rowSums(initial) - 1)) < 1e-6, max(abs(rowSums(final) - 1)) < 1e-6)
write.table(initial[, types], file.path(out, '02_bayesprism/theta_initial.tsv'), sep = '\t', col.names = NA, quote = FALSE)
write.table(final[, types], file.path(out, '02_bayesprism/theta_final.tsv'), sep = '\t', col.names = NA, quote = FALSE)
write.table(bp@posterior.initial.cellState@theta.cv[, types], file.path(out, '02_bayesprism/theta_initial_cv.tsv'), sep = '\t', col.names = NA, quote = FALSE)
write.table(bp@posterior.theta_f@theta.cv[, types], file.path(out, '02_bayesprism/theta_final_cv.tsv'), sep = '\t', col.names = NA, quote = FALSE)
writeLines(c(paste('slots', paste(slotNames(bp), collapse = ',')), paste('initial_Z_dimensions', paste(dim(bp@posterior.initial.cellType@Z), collapse = ' x ')), 'get.exp(type) = posterior.initial.cellType@Z; not updated-final-theta expression'), file.path(out, '02_bayesprism/posterior_output_contract.txt'))
writeLines(paste('BAYESPRISM_COMPLETE', format(Sys.time(), tz = 'Asia/Shanghai', usetz = TRUE)), file.path(out, 'logs/current_stage.txt'))
cat('BAYESPRISM_COMPLETE\n')
